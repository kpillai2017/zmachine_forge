def _neg(opcode: str):
    """A predicate that is the OPPOSITE of an opcode: G=? is 'not jl'."""
    return lambda g, e, label, jump_if: g.simple_branch(opcode, e, label, not jump_if)


def _op(opcode: str):
    return lambda g, e, label, jump_if: g.simple_branch(opcode, e, label, jump_if)


